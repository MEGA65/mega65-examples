var xbuffer: [COLS]u8 = undefined;
var ybuffer: [ROWS]u8 = undefined;
var c1A: u8 = 0;
var c1B: u8 = 0;
var c2A: u8 = 0;
var c2B: u8 = 0;

fn draw() void {
    var c1a = c1A;
    var c1b = c1B;
    for (&ybuffer) |*yb| {
        yb.* = sinustable[c1a] +% sinustable[c1b];
        c1a = c1a +% 4;
        c1b = c1b +% 9;
    }
    c1A = c1A +% 3;
    c1B = c1B -% 5;

    var c2a = c2A;
    var c2b = c2B;
    for (&xbuffer) |*xb| {
        xb.* = sinustable[c2a] +% sinustable[c2b];
        c2a = c2a +% 3;
        c2b = c2b +% 7;
    }
    c2A = c2A +% 2;
    c2B = c2B -% 3;

    // Bounded row/col: no overflow check, so Debug links without an `abort`.
    for (ybuffer, 0..) |yb, row| {
        for (xbuffer, 0..) |xb, col| screen[row * COLS + col] = xb +% yb;
    }
}

fn generate_charset() void {
    const bits = [_]u8{ 1, 2, 4, 8, 16, 32, 64, 128 };
    for (sinustable, 0..) |sine, cnt| {
        for (0..8) |i| {
            var char_pattern: u8 = 0;
            for (0..8) |j| {
                if (mega65.rand8(0xff) > sine) char_pattern |= bits[j];
            }
            charset[cnt * 8 + i] = char_pattern;
        }
    }
}

/// Set MEGA65 speed to 3.5 Mhz.
fn speed_mode3() void {
    mmio(VICIV_CONTROLB).* |= 0b01000000; // set FAST bit
    mmio(VICIV_CONTROLC).* &= 0b10111111; // unset VFAST
}

export fn main() void {
    generate_charset();
    speed_mode3();
    mega65.setcharsetaddr(CHARSET_ADDRESS);
    while (true) draw();
}
