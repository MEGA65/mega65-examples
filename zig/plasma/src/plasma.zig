//! MEGA65 plasma effect, a zig port of c/plasma/plasma.c.
//!
//! Sourced from cc65/samples/cbm: 2001 by groepaz, cleaned up and ported by
//! Ullrich von Bassewitz, MEGA65 adaptation by wombat (2022), which also drops
//! the clock to 3.5 MHz.
//!
//! The arithmetic wraps, as it does in the C original.
const mega65 = @import("mega65");

const COLS = 80;
const ROWS = 25;
const SINESIZE = 256;
const SCREEN_ADDRESS = 0x0800;
const CHARSET_ADDRESS = 0x3000;
const VICIV_CONTROLB = 0xd031;
const VICIV_CONTROLC = 0xd054;

const screen: [*]volatile u8 = @ptrFromInt(SCREEN_ADDRESS);
const charset: [*]volatile u8 = @ptrFromInt(CHARSET_ADDRESS);

fn mmio(comptime addr: usize) *volatile u8 {
    return @ptrFromInt(addr);
}

